-- Run once in the Supabase SQL Editor to enable private study notes
-- for an existing VidyaPath project.

create table if not exists public.study_notes (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    source_filename text not null,
    source_location text not null,
    note text not null check (length(note) <= 3000),
    created_at timestamptz not null default now()
);

create index if not exists study_notes_user_created_idx
    on public.study_notes (user_id, created_at desc);

alter table public.study_notes enable row level security;

drop policy if exists "Learners read their own study notes" on public.study_notes;
create policy "Learners read their own study notes"
    on public.study_notes for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Learners add their own study notes" on public.study_notes;
create policy "Learners add their own study notes"
    on public.study_notes for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Learners delete their own study notes" on public.study_notes;
create policy "Learners delete their own study notes"
    on public.study_notes for delete to authenticated
    using ((select auth.uid()) = user_id);
