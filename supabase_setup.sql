insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'course-files',
    'course-files',
    false,
    209715200,
    array[
        'application/pdf',
        'application/vnd.openxmlformats-officedocument.presentationml.presentation'
    ]
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Learners list their own course files" on storage.objects;
create policy "Learners list their own course files"
    on storage.objects for select to authenticated
    using (
        bucket_id = 'course-files'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
    );

drop policy if exists "Learners upload their own course files" on storage.objects;
create policy "Learners upload their own course files"
    on storage.objects for insert to authenticated
    with check (
        bucket_id = 'course-files'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
    );

drop policy if exists "Learners delete their own course files" on storage.objects;
create policy "Learners delete their own course files"
    on storage.objects for delete to authenticated
    using (
        bucket_id = 'course-files'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
    );
