-- Run once in the Supabase SQL Editor for the VidyaPath project.
-- The application uses the signed-in user's JWT and never uses a service-role key.

create table if not exists public.quiz_results (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    topic text not null,
    score integer not null check (score >= 0),
    total integer not null check (total > 0),
    difficulty text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.used_questions (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    topic_key text not null,
    question text not null,
    created_at timestamptz not null default now(),
    unique (user_id, topic_key, question)
);

create table if not exists public.video_sources (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    video_id text not null,
    title text not null,
    url text not null,
    segments jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now(),
    unique (user_id, video_id)
);

create table if not exists public.tutor_history (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    question text not null,
    answer text not null,
    sources jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.study_notes (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    source_filename text not null,
    source_location text not null,
    note text not null check (length(note) <= 3000),
    created_at timestamptz not null default now()
);

create index if not exists tutor_history_user_created_idx
    on public.tutor_history (user_id, created_at desc);
create index if not exists study_notes_user_created_idx
    on public.study_notes (user_id, created_at desc);

alter table public.quiz_results enable row level security;
alter table public.used_questions enable row level security;
alter table public.video_sources enable row level security;
alter table public.tutor_history enable row level security;
alter table public.study_notes enable row level security;

drop policy if exists "Learners read their own quiz results" on public.quiz_results;
create policy "Learners read their own quiz results"
    on public.quiz_results for select to authenticated
    using ((select auth.uid()) = user_id);

