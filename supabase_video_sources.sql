-- Run once in the Supabase SQL Editor to enable private, account-scoped YouTube lesson outlines.
create table if not exists public.video_sources (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    video_id text not null,
    title text not null,
    url text not null,
    segments jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now(),
    unique (user_id, video_id)
);

alter table public.video_sources enable row level security;

drop policy if exists "Learners read their own video sources" on public.video_sources;
create policy "Learners read their own video sources"
    on public.video_sources for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Learners add their own video sources" on public.video_sources;
create policy "Learners add their own video sources"
    on public.video_sources for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Learners update their own video sources" on public.video_sources;
create policy "Learners update their own video sources"
    on public.video_sources for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

drop policy if exists "Learners delete their own video sources" on public.video_sources;
create policy "Learners delete their own video sources"
    on public.video_sources for delete to authenticated
    using ((select auth.uid()) = user_id);
