-- Run once in the Supabase SQL Editor to enable saved tutor history
-- for an existing VidyaPath project.

create table if not exists public.tutor_history (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    question text not null,
    answer text not null,
    sources jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists tutor_history_user_created_idx
    on public.tutor_history (user_id, created_at desc);

alter table public.tutor_history enable row level security;

drop policy if exists "Learners read their own tutor history" on public.tutor_history;
create policy "Learners read their own tutor history"
    on public.tutor_history for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Learners add their own tutor history" on public.tutor_history;
create policy "Learners add their own tutor history"
    on public.tutor_history for insert to authenticated
    with check ((select auth.uid()) = user_id);
